/** Builds Stubby's shared Corner table (see gen-corner-home.ts). Pure apart from the app data it reads. */
import { CORNER_GUIDES } from "../src/app/data/cornerGuides.ts";
import { CORNER_PREP } from "../src/app/data/cornerPrep.ts";
import { CURATED_CORNERS } from "../src/app/data/curatedCorners.ts";
import { allSubHobbies } from "../src/app/data/hobbies.ts";

export interface CornerHomeEntry {
  key: string;
  name: string;
  step: string;
  /** Up to 3 plain needs, from the curated Corner or cornerPrep.ts. */
  needs: string[];
  /** The guide step works at home: not outdoors, not with other people, not adults only. */
  atHome: boolean;
}

export function cornerHomeEntries(): CornerHomeEntry[] {
  return Object.entries(CORNER_GUIDES)
    .map(([key, g]) => {
      const [space, slug] = key.split("/");
      const name = allSubHobbies.find((s) => s.hobbySlug === space && s.slug === slug)?.label ?? slug;
      const curated = CURATED_CORNERS.find((c) => c.spaceSlug === space && c.slug === slug);
      const needs = (curated?.needs ?? CORNER_PREP[key]?.needs ?? []).slice(0, 3);
      return { key, name, step: g.step.trim(), needs, atHome: !g.adultsOnly && g.where !== "outdoors" && g.together !== "together" && g.step.trim().length > 0 };
    })
    .sort((a, b) => a.key.localeCompare(b.key));
}

export function renderCornerHome(entries: readonly CornerHomeEntry[]): string {
  const rows = entries.map((e) => `  ${JSON.stringify(e.key)}: { name: ${JSON.stringify(e.name)}, step: ${JSON.stringify(e.step)}, needs: ${JSON.stringify(e.needs)}, atHome: ${e.atHome} },`);
  return [
    "// Generated by scripts/gen-corner-home.ts from src/app/data (cornerGuides, cornerPrep, curatedCorners,",
    "// hobbies). Do not edit: run `npx tsx scripts/gen-corner-home.ts`. src/app/lib/cornerHome.test.ts",
    "// fails when this falls behind the app's data. Pure data, no imports: Stubby's function reads it.",
    "",
    "export interface CornerHome {",
    "  name: string;",
    "  step: string;",
    "  needs: string[];",
    "  atHome: boolean;",
    "}",
    "",
    "export const CORNER_HOME: Readonly<Record<string, CornerHome>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}
